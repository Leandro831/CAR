    public void cargarUsuarios(int altoVentana)
    {
        this.panelUsuarios.setPreferredSize(null);
        this.panelUsuarios.removeAll();
        this.panelNuevo.setAlignmentX(Component.LEFT_ALIGNMENT);
        this.panelNuevo.setMaximumSize(new Dimension(Integer.MAX_VALUE, this.panelNuevo.getPreferredSize().height));
        this.panelUsuarios.add(this.panelNuevo);
        this.panelUsuarios.setLayout(new BoxLayout(this.panelUsuarios, BoxLayout.Y_AXIS));
        for (Usuario usuario : GestorUsuarios.getUsuarios()) 
        {
            LineaUsuario linea = new LineaUsuario(usuario);
            linea.setAlignmentX(Component.LEFT_ALIGNMENT);
            linea.setMaximumSize(new Dimension(Integer.MAX_VALUE, linea.getPreferredSize().height));
            linea.setPreferredSize(new Dimension(525, 90));
            this.panelUsuarios.add(linea);
            linea.agregarClick(new java.awt.event.MouseAdapter() {
                @Override
                public void mousePressed(java.awt.event.MouseEvent evt) {
                    lineaUsuarioMousePressed(evt, usuario);
                }
            });
        }
        this.panelUsuarios.revalidate();
        this.panelDentro.revalidate();
        this.panelDentro.doLayout();
        int altoContenido = this.panelUsuarios.getPreferredSize().height + 4;
        int reservado = 500;
        int altoMaximo = Math.max(altoVentana - reservado, 120);
        int alto = Math.max(Math.min(altoContenido, altoMaximo), 160);
        this.panelScroll.setPreferredSize(new Dimension(525, alto));
        this.panelDentro.revalidate();
        this.panelDentro.repaint();
        this.panelScroll.revalidate();
        this.revalidate();
        SwingUtilities.invokeLater(() -> {
            this.panelScroll.getVerticalScrollBar().setValue(0);
        });
    }
    
    public void setAlSeleccionarUsuario(Consumer<Usuario> accion) {
        this.alSeleccionarUsuario = accion;
    }
    
    private void lineaUsuarioMousePressed(MouseEvent evt, Usuario usuario)
    {
        if (alSeleccionarUsuario != null) alSeleccionarUsuario.accept(usuario);
    }

