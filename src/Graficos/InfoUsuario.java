    public void setUsuario(Usuario usuario)
    {
        this.textoNombre.setText(usuario.getNombre());
        this.username.setText(usuario.getNombreUsuario());
        this.switchBoton.setActivo(usuario.isActivo());
        this.estado.setText(usuario.isActivo() ? "Activo" : "Inactivo");
        this.switchBoton.setEnabled(true);
        this.id.setText(String.valueOf(usuario.getId()));
        if(usuario.isAdmin())
            this.rol.setText("Administrador");
        else
            this.rol.setText("Empleado");
        this.usuario = usuario;
    }

