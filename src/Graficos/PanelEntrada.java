    public void cargarProductos()
    {
        DefaultComboBoxModel<String> modelo = new DefaultComboBoxModel<>();
        modelo.addElement("Elija el producto");
        for (Producto producto : GestorInventario.getProductos())
            modelo.addElement(producto.getNombre());
        this.menuProductos.setModel(modelo);
        this.menuProductos.setSelectedIndex(0);
    }
    
    public void validarCampo()
    {
        boolean producto = this.menuProductos.getSelectedItem() != null && !this.menuProductos.getSelectedItem().equals("Elija el producto");
        boolean cantidad = validarCantidad();
        this.textoCantidad.setEnabled(producto);
        this.botonRegistrar.setEnabled(cantidad && producto);
    }
    
    private boolean validarCantidad()
    {
        if(this.campoCantidad.getText().isBlank() || this.campoCantidad.getText().equals("Ingrese la cantidad"))
        {
            this.mensajeError.setVisible(false);
            return false;
        }
        boolean valido;
        try
        {
            valido = Integer.parseInt(this.campoCantidad.getText()) >= 0;
        }
        catch(NumberFormatException e)
        {
            valido = false;
        }
        this.mensajeError.setVisible(!valido);
        return valido;
    }
    
    public void limpiar()
    {
        this.menuProductos.setSelectedIndex(0);
        this.campoCantidad.setText("Ingrese la cantidad");
        this.campoCantidad.setForeground(new Color(200, 200, 200));
    }
    
    public int getCantidad()
    {
        return Integer.parseInt(this.campoCantidad.getText());
    }
    
    public void setProducto(Producto producto)
    {
        this.menuProductos.setSelectedItem(producto.getNombre());
    }

