    public void mostrarReporte(int umbral)
    {
        this.panelDentro.setPreferredSize(null);
        this.panelDentro.removeAll();
        this.textoDescripcion = new JLabel();
        textoDescripcion.setFont(new java.awt.Font("Inter", 0, 18));
        this.panelDentro.add(this.textoDescripcion);
        this.textoDescripcion.setText("<html>Los siguientes productos tienen una cantidad de unidades disponibles<br>inferior o igual al umbral de " + umbral + " unidades:");
        this.panelDentro.add(Box.createVerticalStrut(20));
        for(Producto producto: GestorInventario.getProductos())
        {
            if(producto.getCantidad() <= umbral)
            {
                JLabel nombre = new JLabel(producto.getNombre());
                nombre.setFont(new Font("Inter", 1, 24));
                JLabel stock = new JLabel("Stock disponible: " + producto.getCantidad());
                stock.setFont(new Font("Inter", 0, 20));
                JLabel proveedor = new JLabel("Proveedor: " + producto.getProveedor());
                proveedor.setFont(new Font("Inter", 0, 20));
                nombre.setAlignmentX(Component.LEFT_ALIGNMENT);
                stock.setAlignmentX(Component.LEFT_ALIGNMENT);
                proveedor.setAlignmentX(Component.LEFT_ALIGNMENT);
                this.panelDentro.add(nombre);
                this.panelDentro.add(Box.createVerticalStrut(4));
                this.panelDentro.add(stock);
                this.panelDentro.add(proveedor);
                this.panelDentro.add(Box.createVerticalStrut(20));
            }
        }
        int altoContenido = this.panelDentro.getPreferredSize().height + 4;
        java.awt.Window ventana = SwingUtilities.getWindowAncestor(this);
        int altoVentana = (ventana != null) ? ventana.getHeight() : java.awt.Toolkit.getDefaultToolkit().getScreenSize().height;
        int reservado = 260;
        int altoMaximo = Math.max(altoVentana - reservado, 120);
        int alto = Math.max(Math.min(altoContenido, altoMaximo), 80);
        this.panelScroll.setPreferredSize(new Dimension(728, alto));
        this.panelDentro.revalidate();
        this.panelDentro.repaint();
        this.panelScroll.revalidate();
        this.revalidate();
        SwingUtilities.invokeLater(() -> {
            this.panelScroll.getVerticalScrollBar().setValue(0);
        });
    }

