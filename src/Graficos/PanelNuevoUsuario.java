    public void validarCampos()
    {
        boolean id = this.validarID();
        boolean nombre = !estaVacio(this.campoNombre, "Ingrese el nombre");
        boolean username = !estaVacio(this.campoUsername, "Ingrese el username");
        boolean password = !estaVacio(this.campoPassword, "Ingrese la contraseña");
        this.botonGuardar.setEnabled(id && nombre && password && username && id);
    }
    
    private boolean estaVacio(JTextField campo, String placeholder)
    {
        return campo.getText().isBlank() || campo.getText().equals(placeholder);
    }
    
    private boolean validarID()
    {
        if (estaVacio(this.campoID, "Ingrese el ID"))
        {
            this.mensajeError.setVisible(false);
            return false;
        }
        boolean valido;
        try
        {
            valido = Long.parseLong(this.campoID.getText()) >= 0;
        }
        catch(NumberFormatException e)
        {
            valido = false;
        }
        this.mensajeError.setVisible(!valido);
        return valido;
    }
    
    public void guardarInfoUsuario()
    {
        this.id = Long.parseLong(campoID.getText().trim());
        this.nombre = campoNombre.getText().trim();
        this.username = campoUsername.getText().trim();
        this.password = campoPassword.getText().trim();
        this.activo = switchBoton.isActivo();
        if(this.menuRol.getSelectedIndex() == 0)
            this.admin = true;
        else
            this.admin = false;
    }
    
    public void limpiar()
    {
        this.campoNombre.setText("Ingrese el nombre");
        this.campoNombre.setForeground(new Color(200, 200, 200));
        this.campoID.setText("Ingrese el ID");
        this.campoID.setForeground(new Color(200, 200, 200));
        this.campoUsername.setText("Ingrese el username");
        this.campoUsername.setForeground(new Color(200, 200, 200));
        this.campoPassword.setText("Ingrese la contraseña");
        this.campoPassword.setForeground(new Color(200, 200, 200));
        this.switchBoton.setActivo(true);
        this.menuRol.setSelectedIndex(0);
    }

